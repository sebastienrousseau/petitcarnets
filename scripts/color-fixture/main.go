// Command color-fixture writes what Bubble Tea's colour profile package
// (github.com/charmbracelet/colorprofile, at the version bubbletea v2.2.0
// pins, with the x/ansi it uses) does with colours and environments, for
// the Rust port to be checked against, and the two tables the port
// carries.
//
// Regenerate from the repository root:
//
//	cd scripts/color-fixture
//	go run . fixture > ../../tests/fixtures/color.tsv
//	go run . palette > ../../src/color/palette.in
//	go run . ansi16 > ../../src/color/ansi16.in
//
// The fixture has three kinds of line, tab separated:
//
//	rgb  #rrggbb  <ANSI256 index>  <ANSI index>
//	idx  <n>      <ANSI index>
//	env  <tty 0|1>  <KEY=VALUE ...>  <profile>
//
// An rgb line is Profile.Convert of that colour to ANSI256 and to ANSI;
// an idx line is Profile.Convert of a 256-colour index to ANSI. An env
// line is Detect with the output a terminal (1) or not (0) and that
// environment. The port reads no terminfo and runs no `tmux info`, so
// the generator makes both fail here: PATH is emptied, and a TERM whose
// terminfo entry says RGB or Tc stops the run.
package main

import (
	"fmt"
	"image/color"
	"os"
	"sort"
	"strings"

	"github.com/charmbracelet/colorprofile"
	"github.com/charmbracelet/x/ansi"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: color-fixture fixture|palette|ansi16")
		os.Exit(2)
	}
	switch os.Args[1] {
	case "fixture":
		fixture()
	case "palette":
		palette()
	case "ansi16":
		ansi16()
	default:
		fmt.Fprintln(os.Stderr, "unknown table", os.Args[1])
		os.Exit(2)
	}
}

// palette writes the RGB value of each of the 256 indexed colours.
func palette() {
	fmt.Println("// Generated by scripts/color-fixture (go run . palette); do not edit.")
	fmt.Println("// The RGB value of each 256-colour index, as x/ansi's IndexedColor.RGBA.")
	fmt.Println("[")
	for i := range 256 {
		r, g, b, _ := ansi.IndexedColor(i).RGBA()
		fmt.Printf("    (%d, %d, %d),\n", r>>8, g>>8, b>>8)
	}
	fmt.Println("]")
}

// ansi16 writes the 16-colour index each 256-colour index becomes.
func ansi16() {
	fmt.Println("// Generated by scripts/color-fixture (go run . ansi16); do not edit.")
	fmt.Println("// The 16-colour index each 256-colour index converts to, as x/ansi's Convert16.")
	fmt.Println("[")
	for i := range 256 {
		fmt.Printf("    %d,\n", int(ansi.Convert16(ansi.IndexedColor(i))))
	}
	fmt.Println("]")
}

// index is a converted colour's palette index.
func index(c color.Color) int {
	switch c := c.(type) {
	case ansi.IndexedColor:
		return int(c)
	case ansi.BasicColor:
		return int(c)
	}
	panic(fmt.Sprintf("unexpected %T", c))
}

// lcg is a small fixed-seed generator, so the fixture never changes.
type lcg uint64

func (l *lcg) next() uint8 {
	*l = *l*6364136223846793005 + 1442695040888963407
	return uint8(*l >> 56)
}

// colours lists every grey, the cube's corners and their neighbours,
// and random colours, without repeats.
func colours() []ansi.RGBColor {
	seen := map[ansi.RGBColor]bool{}
	var out []ansi.RGBColor
	add := func(c ansi.RGBColor) {
		if !seen[c] {
			seen[c] = true
			out = append(out, c)
		}
	}
	for v := range 256 {
		add(ansi.RGBColor{R: uint8(v), G: uint8(v), B: uint8(v)})
	}
	levels := []int{0, 0x5f, 0x87, 0xaf, 0xd7, 0xff, 47, 48, 114, 115, 238, 239}
	for _, r := range levels {
		for _, g := range levels {
			for _, b := range []int{0, 0x87, 0xff, 48, 115} {
				add(ansi.RGBColor{R: uint8(r), G: uint8(g), B: uint8(b)})
			}
		}
	}
	rng := lcg(1)
	for len(out) < 4096 {
		add(ansi.RGBColor{R: rng.next(), G: rng.next(), B: rng.next()})
	}
	return out
}

func fixture() {
	_ = os.Setenv("PATH", "")
	fmt.Println("# Generated by scripts/color-fixture (go run . fixture); do not edit.")
	fmt.Println("# rgb #rrggbb ansi256 ansi | idx n ansi | env tty vars profile")
	for _, c := range colours() {
		fmt.Printf("rgb\t#%02x%02x%02x\t%d\t%d\n", c.R, c.G, c.B,
			index(colorprofile.ANSI256.Convert(c)), index(colorprofile.ANSI.Convert(c)))
	}
	for i := range 256 {
		fmt.Printf("idx\t%d\t%d\n", i, index(colorprofile.ANSI.Convert(ansi.IndexedColor(i))))
	}
	for _, e := range environments() {
		for _, tty := range []bool{false, true} {
			env := e
			flag := 0
			if tty {
				env = append(append([]string{}, e...), "TTY_FORCE=1")
				flag = 1
			}
			if t := term(env); t != "" && colorprofile.Terminfo(t) == colorprofile.TrueColor &&
				colorprofile.Env([]string{"TERM=" + t}) != colorprofile.TrueColor {
				panic("terminfo says truecolor for " + t)
			}
			fmt.Printf("env\t%d\t%s\t%s\n", flag, strings.Join(e, " "),
				colorprofile.Detect(nil, env))
		}
	}
}

// term is TERM in env, if set.
func term(env []string) string {
	for _, kv := range env {
		if v, ok := strings.CutPrefix(kv, "TERM="); ok {
			return v
		}
	}
	return ""
}

// environments crosses terminals with colour settings.
func environments() [][]string {
	terms := []string{"", "TERM=", "TERM=dumb", "TERM=xterm", "TERM=xterm-256color",
		"TERM=screen", "TERM=screen-256color", "TERM=tmux-256color", "TERM=xterm-kitty",
		"TERM=alacritty", "TERM=xterm-direct", "TERM=vt100", "TERM=linux", "TERM=foot",
		"TERM=wezterm", "TERM=rxvt-unicode-256color"}
	extras := [][]string{
		nil,
		{"NO_COLOR=1"},
		{"NO_COLOR=true"},
		{"NO_COLOR=0"},
		{"NO_COLOR=yes"},
		{"CLICOLOR=1"},
		{"CLICOLOR=0"},
		{"CLICOLOR_FORCE=1"},
		{"CLICOLOR_FORCE=1", "NO_COLOR=1"},
		{"COLORTERM=truecolor"},
		{"COLORTERM=24bit"},
		{"COLORTERM=yes"},
		{"COLORTERM=TrueColor"},
		{"COLORTERM=256"},
		{"COLORTERM=truecolor", "NO_COLOR=1"},
		{"TMUX=/tmp/tmux-1000/default,1,0"},
		{"TMUX=/tmp/tmux-1000/default,1,0", "COLORTERM=truecolor"},
		{"WT_SESSION=abc"},
		{"GOOGLE_CLOUD_SHELL=true"},
		{"CLICOLOR_FORCE=1", "COLORTERM=truecolor"},
		{"TTY_FORCE=0"},
	}
	var out [][]string
	for _, t := range terms {
		for _, x := range extras {
			var env []string
			if t != "" {
				env = append(env, t)
			}
			env = append(env, x...)
			sort.Strings(env)
			out = append(out, env)
		}
	}
	return out
}
