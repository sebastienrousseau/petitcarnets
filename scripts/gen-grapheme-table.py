#!/usr/bin/env python3
"""Write src/unicode/grapheme_table.in from uniseg's grapheme break table.

Bubble Tea's input reader splits text into grapheme clusters with
github.com/rivo/uniseg; the Rust port uses the same property table, so
both split text the same way. Hangul syllables (LV and LVT) are left out:
they follow a formula, applied in src/unicode/grapheme.rs. Adjacent
ranges with the same property are merged.

Usage, from the repository root (needs Go, for the module cache):

    (cd scripts/input-fixture && go mod download github.com/rivo/uniseg)
    python3 scripts/gen-grapheme-table.py
"""

import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "unicode" / "grapheme_table.in"
PROPS = ["Any", "Prepend", "CR", "LF", "Control", "Extend", "RegionalIndicator",
         "SpacingMark", "L", "V", "T", "LV", "LVT", "ZWJ", "ExtendedPictographic"]
ENTRY = re.compile(r"\{0x([0-9A-F]+), 0x([0-9A-F]+), pr(\w+)\}")


def source():
    moddir = subprocess.run(
        ["go", "list", "-m", "-f", "{{.Dir}}", "github.com/rivo/uniseg"],
        cwd=ROOT / "scripts" / "input-fixture", capture_output=True, text=True, check=True,
    ).stdout.strip()
    return Path(moddir) / "graphemeproperties.go", Path(moddir).name


def ranges(path):
    text = path.read_text()
    table = text[text.index("var graphemeCodePoints"):]
    merged = []
    for start, end, prop in ENTRY.findall(table):
        start, end, prop = int(start, 16), int(end, 16), PROPS.index(prop)
        if 0xAC00 <= start <= 0xD7A3 and prop in (PROPS.index("LV"), PROPS.index("LVT")):
            continue
        if merged and merged[-1][1] + 1 == start and merged[-1][2] == prop:
            merged[-1][1] = end
        else:
            merged.append([start, end, prop])
    return merged


def main():
    path, version = source()
    merged = ranges(path)
    words = []
    for start, end, prop in merged:
        for word in (start | prop << 24, end):
            words.append(f"0x{word >> 16:04X}_{word & 0xFFFF:04X}")
    # Three ranges (six words) per line, so a range never spans two lines.
    lines = ["    " + " ".join(w + "," for w in words[i:i + 6]) for i in range(0, len(words), 6)]
    # A data file, pulled in with `include!` by src/unicode/grapheme.rs:
    # an array expression, so it needs no formatting exemption and is not
    # counted as code by the complexity gate.
    OUT.write_text(
        f"// Grapheme break properties, generated by scripts/gen-grapheme-table.py\n"
        f"// from {version} (Unicode 15.0.0); do not edit. {len(words)} words.\n"
        "[\n" + "\n".join(lines) + "\n]\n"
    )
    print(f"{len(merged)} ranges written to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
